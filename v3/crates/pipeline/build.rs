//! pipeline build script — Phase 1 YOLO posture (parse.md §14.4).
//!
//! Does NOT invoke `tree-sitter`. Each pattern op commits its own
//! `src/parser.c` via `just regen-op <name>`. This script only:
//!
//!   1. Walks `src/ops/*/grammar.js` to find declared pattern ops.
//!   2. For each, expects `ops/<name>/src/parser.c` (+ optional
//!      `scanner.c`) to exist; compiles via `cc::Build` into per-op
//!      static libs.
//!   3. Emits `$OUT_DIR/op_languages.rs`: a trivial match over op
//!      names binding to the `extern "C"` language fns.
//!
//! Keeps dependency footprint minimal: `cc` only. No `tree-sitter-cli`,
//! no Node. If `parser.c` is missing, the build fails with a pointer
//! to the `just` recipe.

use std::env;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let ops_dir = manifest_dir.join("src").join("ops");
    println!("cargo:rerun-if-changed={}", ops_dir.display());

    let mut pattern_ops: Vec<String> = Vec::new();

    if let Ok(entries) = fs::read_dir(&ops_dir) {
        for entry in entries.flatten() {
            let path = entry.path();
            if !path.is_dir() {
                continue;
            }
            let grammar_js = path.join("grammar.js");
            if !grammar_js.exists() {
                continue;
            }
            let op_name = path
                .file_name()
                .and_then(|n| n.to_str())
                .expect("op folder name")
                .to_string();
            compile_op_parser(&path, &op_name);
            pattern_ops.push(op_name);
        }
    }

    pattern_ops.sort();
    emit_op_languages(&pattern_ops);
}

fn compile_op_parser(op_dir: &Path, op_name: &str) {
    let src = op_dir.join("src").join("parser.c");
    if !src.exists() {
        panic!(
            "pattern op `{name}` has grammar.js but no committed src/parser.c at {path}.\n\
             Regenerate with: `just regen-op {name}`",
            name = op_name,
            path = src.display(),
        );
    }
    println!("cargo:rerun-if-changed={}", src.display());

    let mut build = cc::Build::new();
    build.include(op_dir.join("src"));
    build.file(&src);

    let scanner = op_dir.join("src").join("scanner.c");
    if scanner.exists() {
        println!("cargo:rerun-if-changed={}", scanner.display());
        build.file(&scanner);
    }

    // Opt out of the warnings tree-sitter-generated parsers trip.
    build
        .warnings(false)
        .flag_if_supported("-std=c11")
        .flag_if_supported("-Wno-unused-parameter")
        .flag_if_supported("-Wno-unused-but-set-variable")
        .flag_if_supported("-Wno-trigraphs");

    build.compile(&format!("sprefa_{}", op_name));
}

fn emit_op_languages(ops: &[String]) {
    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());
    let out = out_dir.join("op_languages.rs");

    let mut s = String::new();
    s.push_str("// GENERATED by pipeline/build.rs — do not edit.\n");
    s.push_str("// See parse.md §14.4.\n\n");

    s.push_str("use tree_sitter::Language;\n\n");

    for op in ops {
        s.push_str(&format!(
            "extern \"C\" {{ fn tree_sitter_sprefa_{op}() -> Language; }}\n"
        ));
    }
    s.push('\n');

    s.push_str("pub fn language_of(name: &str) -> Option<Language> {\n");
    s.push_str("    match name {\n");
    for op in ops {
        s.push_str(&format!(
            "        \"{op}\" => Some(unsafe {{ tree_sitter_sprefa_{op}() }}),\n"
        ));
    }
    s.push_str("        _ => None,\n");
    s.push_str("    }\n}\n\n");

    s.push_str("pub fn highlights_of(name: &str) -> Option<&'static str> {\n");
    s.push_str("    match name {\n");
    for op in ops {
        s.push_str(&format!(
            "        \"{op}\" => Some(include_str!(concat!(\n\
             \x20           env!(\"CARGO_MANIFEST_DIR\"),\n\
             \x20           \"/src/ops/{op}/queries/highlights.scm\"))),\n",
        ));
    }
    s.push_str("        _ => None,\n");
    s.push_str("    }\n}\n");

    fs::write(&out, s).expect("write op_languages.rs");
}
