% v1-scale-gen.pl: emit the plain Datalog shapes through the existing v1
% literal-TS emitter. The keyed-replace edge shape has no v1 AST equivalent.

:- module(v1_scale_gen, [write_program/2]).

:- use_module('../../prolog/src/emit_ts').

:- op(1150, xfx, <-).

write_program(Shape, Path) :-
    memberchk(Shape, [s2, s3]),
    v1_program(Shape, Decls, Rules),
    maplist(emit_ts:decl_ts, Decls, DeclLines),
    maplist(emit_ts:rule_ts(Decls), Rules, RuleLines),
    atomic_list_concat(DeclLines, '\n', DeclsBlock),
    atomic_list_concat(RuleLines, '\n', RulesBlock),
    format(atom(Body),
           'export const program: Program = {~n  rels: [~n~w~n  ],~n  rules: [~n~w~n  ],~n};~n',
           [DeclsBlock, RulesBlock]),
    emit_ts:used_helpers(Body, Helpers),
    atomic_list_concat(Helpers, ', ', HelperList),
    format(atom(Text),
           '/** GENERATED by bench/v1-scale-gen.pl for shape ~w. Do not edit. */~nimport { type Program, ~w } from "../lower/ast.ts";~n~n~w',
           [Shape, HelperList, Body]),
    file_directory_name(Path, Dir),
    make_directory_path(Dir),
    setup_call_cleanup(open(Path, write, Stream), write(Stream, Text), close(Stream)),
    format('wrote ~w~n', [Path]).

v1_program(s2,
           [ edb(c, [key, payload]),
             edb(b_link, [key, mid]),
             edb(a_link, [mid, value]),
             idb(b, [key, mid]),
             idb(a, [key, value])
           ],
           [ (b(BKey, BMid) <- (c(BKey, BPayload), b_link(BKey, BMid))),
             (a(AKey, AValue) <- (b(AKey, AMid), a_link(AMid, AValue)))
           ]).
v1_program(s3,
           [ edb(left, [left]),
             edb(right, [right]),
             idb(combined, [left, right])
           ],
           [ (combined(Left, Right) <- (left(Left), right(Right))) ]).
