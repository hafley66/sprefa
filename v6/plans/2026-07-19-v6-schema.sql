-- V6 schema, ANSI SQL. Rendered per dialect by sea-query at runtime.
--
-- Rulings this encodes:
--   * No REFERENCES clauses: _id is the contract, an orphan-scan rail checks.
--   * Surrogates are dense identities or content hashes; never hashed ints.
--   * Composite keys where the key is composite; surrogate only where
--     something must point at the row cheaply.
--   * Entity tables are WRITE-ONCE. Mutable state gets its own table.
--   * Files are owned by nothing. Repo membership is ancestry, not a column.
--   * Dirs recurse, files do not (globs must never walk the 1M-row table).
--   * History is stored git-shaped (content-addressed, shared across revs);
--     the flat per-rev index is materialized only for subscribed revs.
--
-- Sizing target: 500 repos. See the table at the end.

-- ============================================================ VOCABULARY

-- Path SEGMENTS, identifiers, kinds. Never a full path, never a coordinate,
-- never a qualified symbol, never a rev-salted id. Dense sequential ids.
CREATE TABLE str (
  str_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  content VARCHAR(4096) NOT NULL UNIQUE
);

-- ============================================================ FILESYSTEM
-- Identity layer. Answers "what exists and where", independent of git.

-- A directory. Recursive parent chain -- dirs are ~15% of file count, so the
-- walk stays over a small hot table. depth is cached to bound the recursion.
CREATE TABLE dir (
  dir_id    INTEGER  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  parent_id INTEGER,                       -- NULL = a filesystem root
  name_id   INTEGER  NOT NULL,             -- -> str, ONE segment
  depth     SMALLINT NOT NULL,
  repo_id   INTEGER,                       -- cached ancestry; NULL = no repo
  UNIQUE (parent_id, name_id)
);
CREATE INDEX dir_by_repo ON dir (repo_id);

-- A file. Owned by nothing. Identity is (where it lives, what it's called).
-- No repo_id, no rev: a file in a worktree, outside git, or in a submodule
-- is the same kind of thing.
CREATE TABLE file (
  file_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dir_id  INTEGER NOT NULL,
  name_id INTEGER NOT NULL,                -- -> str, the basename
  UNIQUE (dir_id, name_id)
);

-- Content, addressed once. Identical bytes across revs OR repos = one row.
CREATE TABLE blob (
  blob_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  content_hash VARBINARY(16) NOT NULL UNIQUE,   -- blake3, truncated
  size_bytes   INTEGER NOT NULL,
  line_count   INTEGER NOT NULL
);

-- Mutable state, kept OUT of the entity tables so `file` is never UPDATEd.
-- rev_id NULL = untracked, or no git present at all. Both are fine.
CREATE TABLE file_head (
  file_id INTEGER PRIMARY KEY,
  blob_id INTEGER NOT NULL,
  rev_id  INTEGER,
  seen_at BIGINT  NOT NULL
);

-- ============================================================ GIT
-- Optional layer. Everything above works with this empty.

-- A repo IS a directory. Membership is ancestry; nested repos and submodules
-- fall out for free.
CREATE TABLE repo (
  repo_id     INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  root_dir_id INTEGER      NOT NULL UNIQUE,
  slug        VARCHAR(255) NOT NULL UNIQUE,
  url         VARCHAR(1024) NOT NULL DEFAULT ''
);

-- A checkout: the main worktree, or a linked `git worktree`. Each has its
-- own directory and its own uncommitted state. Making these first-class is
-- also what lets the daemon TELL a worktree from a repo (V5 failure class
-- 14: agent worktrees minting ~600MB orphan roots each).
CREATE TABLE worktree (
  worktree_id  INTEGER  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  repo_id      INTEGER  NOT NULL,
  root_dir_id  INTEGER  NOT NULL UNIQUE,
  is_linked    SMALLINT NOT NULL DEFAULT 0  -- 1 = `git worktree`, .git is a FILE
);

-- One row per rev. kind is what makes WORK a first-class citizen rather
-- than a special case threaded through every query:
--   kind 0 = commit    : git_sha set, immutable, tree from git objects
--   kind 1 = worktree  : git_sha NULL, mutable, tree computed from disk
-- Every downstream table (rev_file, node_*, rel_state, subscription) keys on
-- rev_id and neither knows nor cares which kind it got.
--
-- seq is a topological sequence: "last touched" needs an ORDER, and rev_id
-- is insertion order, not commit order. A worktree rev sorts after its base.
CREATE TABLE rev (
  rev_id      INTEGER  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  repo_id     INTEGER  NOT NULL,
  kind        SMALLINT NOT NULL DEFAULT 0,
  git_sha     VARBINARY(20),               -- NULL iff kind = 1
  worktree_id INTEGER,                     -- NOT NULL iff kind = 1
  base_rev_id INTEGER,                     -- what the worktree is checked out from
  seq         BIGINT   NOT NULL,
  observed_at BIGINT   NOT NULL,
  UNIQUE (repo_id, git_sha),
  UNIQUE (worktree_id)                     -- one live WORK rev per worktree
);

-- The commit DAG. ord 0 = first parent. Merges get ord 1..n.
-- Reachability over this is the same walk as any other graph family.
CREATE TABLE rev_parent (
  rev_id        INTEGER  NOT NULL,
  parent_rev_id INTEGER  NOT NULL,
  ord           SMALLINT NOT NULL,
  PRIMARY KEY (rev_id, ord)
);
CREATE INDEX rev_parent_by_parent ON rev_parent (parent_rev_id);

-- Content-addressed directory listing -- a git tree. An unchanged directory
-- is ONE hash comparison and the whole subtree is skipped unread. This is
-- what makes 500 repos affordable: an unchanged root hash skips a repo.
CREATE TABLE tree (
  tree_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tree_hash VARBINARY(16) NOT NULL UNIQUE  -- over the (name, child) listing
);

-- The listing itself. Shared by EVERY rev whose tree hashes to this -- which
-- is why history does not cost rows per rev per file.
CREATE TABLE tree_entry (
  tree_id    INTEGER  NOT NULL,
  name_id    INTEGER  NOT NULL,            -- -> str, one segment
  child_kind SMALLINT NOT NULL,            -- 0 = blob, 1 = tree
  child_id   INTEGER  NOT NULL,            -- blob_id or tree_id per kind
  PRIMARY KEY (tree_id, name_id)
);

-- commit -> root tree.
CREATE TABLE rev_root (
  rev_id  INTEGER PRIMARY KEY,
  tree_id INTEGER NOT NULL
);

-- Flat (rev, file) index. NOT the source of truth -- `tree` is. Materialized
-- ONLY for revs under subscription (typically each repo's HEAD), because
-- storing it for all history is rows = revs x files, which does not fit.
-- Dropped when its rev loses its last subscriber.
CREATE TABLE rev_file (
  rev_id  INTEGER NOT NULL,
  file_id INTEGER NOT NULL,
  blob_id INTEGER NOT NULL,
  PRIMARY KEY (rev_id, file_id)
);
CREATE INDEX rev_file_by_file ON rev_file (file_id);

-- ============================================================ GRAPH
-- One shape, four instantiations: <family> in {df, call, type, module}.
-- Separate tables so index locality holds and a family goes cold alone.

-- A node IS its coordinate. repo_id absent on purpose: reachable via rev_id
-- or file_id, and copying it costs 150M rows.
CREATE TABLE node_<family> (
  node_id    INTEGER  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rev_id     INTEGER  NOT NULL,
  file_id    INTEGER  NOT NULL,
  byte_start INTEGER  NOT NULL,            -- line/col derived, never stored
  byte_len   INTEGER  NOT NULL,
  kind       SMALLINT NOT NULL,            -- enum ordinal, not a string id
  name_id    INTEGER,                      -- -> str, NULL when anonymous
  weight     INTEGER  NOT NULL DEFAULT 1,  -- Z-set multiplicity
  UNIQUE (rev_id, file_id, byte_start, kind)
);
CREATE INDEX node_<family>_by_scope ON node_<family> (rev_id, file_id);
CREATE INDEX node_<family>_by_name  ON node_<family> (name_id);

-- Composite key, no surrogate: nothing points at an edge.
CREATE TABLE edge_<family> (
  src_id INTEGER  NOT NULL,
  dst_id INTEGER  NOT NULL,
  kind   SMALLINT NOT NULL,
  weight INTEGER  NOT NULL DEFAULT 1,
  PRIMARY KEY (src_id, dst_id, kind)
);
CREATE INDEX edge_<family>_by_dst ON edge_<family> (dst_id);

-- ============================================================ DEMAND

-- Program rel names, dense ids. Closed set (~330), ids stay 1-2 bytes.
CREATE TABLE rel_name (
  rel_id INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name   VARCHAR(255) NOT NULL UNIQUE
);

-- The persisted verifying trace. rel_id is an SCC id for a recursive group.
-- wake:   SELECT DISTINCT rel_id FROM trace_dep WHERE dep_rel_id = ?
-- verify: SELECT dep_rel_id, dep_digest FROM trace_dep WHERE rel_id = ?
CREATE TABLE trace_dep (
  rel_id     INTEGER NOT NULL,
  dep_rel_id INTEGER NOT NULL,
  dep_digest VARBINARY(8) NOT NULL,
  PRIMARY KEY (rel_id, dep_rel_id)
);
CREATE INDEX trace_dep_by_dep ON trace_dep (dep_rel_id);

-- Subscription ROOTS. trace_dep supplies the edges; this supplies the roots,
-- and the two together ARE the subscription graph. Traversed DOWN from these
-- rows you get the demand cone; traversed UP from a changed rel you get the
-- wake set. One edge table, two directions.
--
-- A refcount is COUNT(*) over this table, never a stored counter -- counters
-- drift, queries do not. Dropping a Sub deletes its row.
--   source: 0 lsp-doc, 1 serve-route, 2 one-shot, 3 watcher
--   standing: 1 = survives restart (routes, watchers); 0 = session-scoped
CREATE TABLE subscription (
  sub_id     INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rel_id     INTEGER      NOT NULL,
  rev_id     INTEGER      NOT NULL,
  source     SMALLINT     NOT NULL,
  owner      VARCHAR(255) NOT NULL,        -- session / route / request id
  standing   SMALLINT     NOT NULL DEFAULT 0,
  created_at BIGINT       NOT NULL
);
CREATE INDEX subscription_by_rel   ON subscription (rel_id, rev_id);
CREATE INDEX subscription_by_owner ON subscription (owner);

-- Materialization registry. status: 0 cold, 1 live, 2 stale.
-- last_read_at/bytes are REPORTING for `dl daemon health`, never an eviction
-- trigger: the tier is syntax (`save`), not policy.
CREATE TABLE rel_state (
  rel_id       INTEGER  NOT NULL,
  rev_id       INTEGER  NOT NULL,
  status       SMALLINT NOT NULL DEFAULT 0,
  saved        SMALLINT NOT NULL DEFAULT 0,  -- 1 iff declared `save`
  row_count    BIGINT   NOT NULL DEFAULT 0,
  bytes        BIGINT   NOT NULL DEFAULT 0,
  last_read_at BIGINT   NOT NULL DEFAULT 0,
  PRIMARY KEY (rel_id, rev_id)
);

-- ============================================================ REL TABLES
-- NOT spine. Runtime DDL on first materialization of a `save` rel; dropped
-- when it stops being saved. Migrations never see these: cache, not schema.
-- A transient rel has no table at all.
CREATE TABLE rel_<name> (
  <col_1> INTEGER NOT NULL,
  <col_n> INTEGER NOT NULL,
  rev_id  INTEGER NOT NULL,
  weight  INTEGER NOT NULL DEFAULT 1,
  PRIMARY KEY (<col_1>, ..., <col_n>, rev_id)
);

-- ============================================================ VIEWS
-- The normalization is for the writer; these are for everyone else.
-- Nothing below stores a byte.

-- Full directory path. The recursion the dir tree costs you, paid once here.
CREATE VIEW v_dir AS
WITH RECURSIVE walk (dir_id, path, repo_id) AS (
  SELECT d.dir_id, s.content, d.repo_id
    FROM dir d JOIN str s ON s.str_id = d.name_id
   WHERE d.parent_id IS NULL
  UNION ALL
  SELECT d.dir_id, w.path || '/' || s.content, d.repo_id
    FROM dir d JOIN walk w ON w.dir_id = d.parent_id
               JOIN str s  ON s.str_id = d.name_id
)
SELECT dir_id, path, repo_id FROM walk;

-- A file as everyone thinks of it: one path string, its repo, its content.
CREATE VIEW v_file AS
SELECT f.file_id,
       vd.path || '/' || s.content AS path,
       vd.repo_id,
       r.slug        AS repo_slug,
       h.blob_id,
       h.rev_id,
       b.size_bytes,
       b.line_count
  FROM file f
  JOIN v_dir vd ON vd.dir_id  = f.dir_id
  JOIN str   s  ON s.str_id   = f.name_id
  LEFT JOIN repo      r ON r.repo_id  = vd.repo_id
  LEFT JOIN file_head h ON h.file_id  = f.file_id
  LEFT JOIN blob      b ON b.blob_id  = h.blob_id;

-- A rev with its repo and a readable sha.
CREATE VIEW v_rev AS
SELECT rv.rev_id, rv.seq, rv.observed_at,
       rp.slug AS repo_slug,
       HEX(rv.git_sha) AS sha
  FROM rev rv JOIN repo rp ON rp.repo_id = rv.repo_id;

-- Commit ancestry, transitively. The DAG walk, named once.
CREATE VIEW v_rev_ancestor AS
WITH RECURSIVE up (rev_id, ancestor_id, dist) AS (
  SELECT rev_id, rev_id, 0 FROM rev
  UNION
  SELECT u.rev_id, p.parent_rev_id, u.dist + 1
    FROM up u JOIN rev_parent p ON p.rev_id = u.ancestor_id
)
SELECT rev_id, ancestor_id, dist FROM up;

-- WORK: the current worktree rev per repo. This is what a bare `scan`
-- resolves to, so a .dl file in a repo reads its own working tree by default.
CREATE VIEW v_work AS
SELECT rv.rev_id, rv.repo_id, rp.slug AS repo_slug,
       w.worktree_id, w.is_linked, vd.path AS worktree_path,
       rv.base_rev_id
  FROM rev rv
  JOIN worktree w  ON w.worktree_id = rv.worktree_id
  JOIN repo     rp ON rp.repo_id    = rv.repo_id
  JOIN v_dir    vd ON vd.dir_id     = w.root_dir_id
 WHERE rv.kind = 1;

-- Live demand: every subscribed (rel, rev) with its current refcount.
-- The refcount is the COUNT, not a column anyone maintains.
CREATE VIEW v_demand AS
SELECT rel_id, rev_id, COUNT(*) AS refs,
       MIN(created_at) AS oldest,
       SUM(standing)   AS standing_refs
  FROM subscription
 GROUP BY rel_id, rev_id;

-- The demand cone: everything that must compute, per subscribed root.
-- trace_dep read DOWNWARD (rel_id -> dep_rel_id).
CREATE VIEW v_cone AS
WITH RECURSIVE cone (root_rel_id, rel_id, rev_id, depth) AS (
  SELECT DISTINCT s.rel_id, s.rel_id, s.rev_id, 0 FROM subscription s
  UNION
  SELECT c.root_rel_id, td.dep_rel_id, c.rev_id, c.depth + 1
    FROM cone c JOIN trace_dep td ON td.rel_id = c.rel_id
)
SELECT root_rel_id, rel_id, rev_id, MIN(depth) AS depth
  FROM cone GROUP BY root_rel_id, rel_id, rev_id;

-- The wake set: given a changed rel, who must be recomputed or marked stale.
-- The SAME trace_dep edges read UPWARD (dep_rel_id -> rel_id).
CREATE VIEW v_wake AS
WITH RECURSIVE up (changed_rel_id, rel_id, depth) AS (
  SELECT dep_rel_id, dep_rel_id, 0 FROM trace_dep
  UNION
  SELECT u.changed_rel_id, td.rel_id, u.depth + 1
    FROM up u JOIN trace_dep td ON td.dep_rel_id = u.rel_id
)
SELECT changed_rel_id, rel_id, MIN(depth) AS depth
  FROM up GROUP BY changed_rel_id, rel_id;

-- "Why is this computing?" -- a rel, its refcount, and which subscription
-- roots reach it. This is `dl daemon subs` as a query.
CREATE VIEW v_why_computing AS
SELECT c.rel_id, c.rev_id, rn.name AS rel_name,
       c.root_rel_id, rr.name AS root_name,
       c.depth, d.refs
  FROM v_cone c
  JOIN rel_name rn ON rn.rel_id = c.rel_id
  JOIN rel_name rr ON rr.rel_id = c.root_rel_id
  LEFT JOIN v_demand d ON d.rel_id = c.root_rel_id AND d.rev_id = c.rev_id;

-- Graph nodes with paths and names resolved. One per family.
-- NOTE: line/col are NOT here -- they need the blob's line index, which is
-- computed in Rust from byte_start. Views resolve ids, never content.
CREATE VIEW v_node_<family> AS
SELECT n.node_id, n.kind, n.byte_start, n.byte_len, n.weight,
       vf.path, vf.repo_slug, n.rev_id,
       s.content AS name
  FROM node_<family> n
  JOIN v_file vf ON vf.file_id = n.file_id
  LEFT JOIN str s ON s.str_id = n.name_id;

-- Edges with both endpoints resolved.
CREATE VIEW v_edge_<family> AS
SELECT e.kind, e.weight,
       sn.path AS src_path, sn.name AS src_name, sn.byte_start AS src_start,
       dn.path AS dst_path, dn.name AS dst_name, dn.byte_start AS dst_start
  FROM edge_<family> e
  JOIN v_node_<family> sn ON sn.node_id = e.src_id
  JOIN v_node_<family> dn ON dn.node_id = e.dst_id;

-- ============================================================ SIZING
-- 500 repos at sprefa density (~300k df nodes, ~260k edges, ~2k files/repo).
--
--   table          rows      id width   note
--   ------------   -------   --------   ------------------------------------
--   repo           500       u16
--   dir            150k      u32        ~15% of file count
--   file           1M        u32        flat; globs never recurse this
--   blob           3M        u32        deduped across revs AND repos
--   str            2-10M     u32        SEGMENTS, not paths: heavy dedup
--   rev            100k      u32        ~200 tracked revs per repo
--   rev_parent     ~110k     u32        most commits have 1 parent
--   tree           ~2M       u32        content-addressed, shared
--   tree_entry     ~15M      u32        the real history cost, shared
--   rev_file       1M        u32        SUBSCRIBED revs only (~1 HEAD/repo)
--   file_head      1M        u32
--   node_*         ~150M     u32        all four families
--   edge_*         ~130M     u32        all four families
--   trace_dep      ~600      u16        per program, not per corpus
--
-- u32 everywhere. Dense assignment means small ids varint-encode to 1-3
-- bytes on SQLite instead of the flat 8 that hash-valued ids force.
-- Crossing 2^32 is a migration, not a corruption; a test asserts the ceiling.

-- ============================================================ DIALECT NOTES
-- SQLite:  every composite-PK table (rev_file, tree_entry, rev_parent,
--          edge_*, trace_dep, rel_state, rel_*) is emitted WITHOUT ROWID via
--          sea-query .extra() -- the table becomes the index instead of
--          paying for both. That is the 256.6MB duplicate-copy bucket in V5.
--          GENERATED BY DEFAULT AS IDENTITY renders as INTEGER PRIMARY KEY
--          (which IS the rowid, and stays dense). Never AUTOINCREMENT.
-- Postgres: composite-PK tables are plain; identity is native; HEX() is
--          ENCODE(sha,'hex'); || concatenation is identical.
