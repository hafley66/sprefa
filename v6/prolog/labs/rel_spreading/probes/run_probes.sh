#!/usr/bin/env bash
# Cross-language ground-truth probes for the rel-spreading lab (Q0).
# Runs every probe under a REAL compiler and writes verbatim output to
# RECEIPTS.md. Nothing here is recalled; every line is captured stdout/stderr.
#
# Run from v6/prolog/labs/rel_spreading:
#   bash probes/run_probes.sh
set -u

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
LAB="$(dirname "$HERE")"
OUT="$LAB/RECEIPTS.md"
WORK="$HERE/.work"
rm -rf "$WORK"
mkdir -p "$WORK"

TSGO="/Users/chrishafley/projects/sprefa/v6/tsv2/node_modules/.bin/tsgo"

emit() { printf '%s\n' "$*" >>"$OUT"; }

: >"$OUT"
emit "# RECEIPTS: cross-language ground truth for rel spreading"
emit ""
emit "Generated by \`probes/run_probes.sh\`. Every block below is VERBATIM"
emit "compiler stdout+stderr, captured at the recorded toolchain version."
emit "Nothing in this file is recalled."
emit ""
emit "## Toolchains"
emit ""
emit '```text'
{
  echo "date: $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "tsc: $(tsc --version 2>&1)"
  if [ -x "$TSGO" ]; then echo "tsgo: $("$TSGO" --version 2>&1)"; else echo "tsgo: NOT PRESENT"; fi
  echo "rustc: $(rustc --version 2>&1)"
  if command -v go >/dev/null 2>&1; then echo "go: $(go version 2>&1)"; else echo "go: N/A, no go toolchain on this machine"; fi
} >>"$OUT"
emit '```'
emit ""

run_ts() {
  local file="$1"
  emit "### TypeScript: \`probes/ts/$(basename "$file")\`"
  emit ""
  emit '```text'
  emit "\$ tsc --noEmit --strict --target es2022 --module esnext --moduleResolution bundler probes/ts/$(basename "$file")"
  ( cd "$LAB" && tsc --noEmit --strict --target es2022 --module esnext --moduleResolution bundler "probes/ts/$(basename "$file")" ) >>"$OUT" 2>&1
  emit "exit: $?"
  if [ -x "$TSGO" ]; then
    emit ""
    emit "\$ tsgo --noEmit --strict --target es2022 --module esnext --moduleResolution bundler probes/ts/$(basename "$file")"
    ( cd "$LAB" && "$TSGO" --noEmit --strict --target es2022 --module esnext --moduleResolution bundler "probes/ts/$(basename "$file")" ) >>"$OUT" 2>&1
    emit "exit: $?"
  fi
  emit '```'
  emit ""
}

run_rust() {
  local file="$1"
  emit "### Rust: \`probes/rust/$(basename "$file")\`"
  emit ""
  emit '```text'
  emit "\$ rustc --edition 2021 --emit=metadata --crate-type bin probes/rust/$(basename "$file")"
  ( cd "$LAB" && rustc --edition 2021 --emit=metadata --crate-type bin -o "$WORK/$(basename "$file").meta" "probes/rust/$(basename "$file")" ) >>"$OUT" 2>&1
  emit "exit: $?"
  emit '```'
  emit ""
}

run_go() {
  local file="$1"
  emit "### Go: \`probes/go/$(basename "$file")\`"
  emit ""
  emit '```text'
  if ! command -v go >/dev/null 2>&1; then
    emit "N/A: no go toolchain on this machine"
    emit '```'
    emit ""
    return
  fi
  emit "\$ go build -o /dev/null probes/go/$(basename "$file")"
  ( cd "$LAB" && GOFLAGS=-mod=mod GO111MODULE=off go build -o /dev/null "probes/go/$(basename "$file")" ) >>"$OUT" 2>&1
  emit "exit: $?"
  emit '```'
  emit ""
}

for case_id in c1 c2 c3 c4 c5 c6 c7; do
  emit "## $(echo "$case_id" | tr '[:lower:]' '[:upper:]')"
  emit ""
  for f in "$HERE"/ts/${case_id}_*.ts; do
    [ -e "$f" ] || continue
    run_ts "$f"
  done
  for f in "$HERE"/rust/${case_id}_*.rs; do
    [ -e "$f" ] || continue
    run_rust "$f"
  done
  for f in "$HERE"/go/${case_id}_*.go; do
    [ -e "$f" ] || continue
    run_go "$f"
  done
done

rm -rf "$WORK"
echo "wrote $OUT"
