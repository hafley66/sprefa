    sub_string(Text, _, _, _, "export const program: Program"),
    sub_string(Text, _, _, _, "edbRel(\"edge\", [\"parent\", \"child\"])"),
    sub_string(Text, _, _, _, "relRef(\"edge\", v(\"parent\"), v(\"child\"))"),
    sub_string(Text, _, _, _, "relRef(\"reach\", v(\"parent\"))"),   % the join, by name
    sub_string(Text, _, _, _, "headVar(\"child\")"),
