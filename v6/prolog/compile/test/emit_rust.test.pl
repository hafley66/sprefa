% plunit tests for v6/prolog/emit_rust.pl, the Rust sibling of emit_ts.pl.
%
% Run: swipl -q -l v6/prolog/compile/test/emit_rust.test.pl -g run_tests -g halt
%
% emit_program/5 walks the same lowered/8 destructure as emit_ts:emit_program/5
% and returns a Rust source document. The tests assert the emitted Text parses
% as the single ProgramJson document the crate's ProgramJson mirror consumes,
% with the emitter-stable fields present and the level/relation data intact.

:- op(1150, xfx, <-).
:- op(1150, xfx, <+).
:- use_module(library(plunit)).
:- use_module(library(json)).
:- use_module(library(lists)).
:- use_module('../../compile',
              [ read_fixture_term/4, program_plan/3, program_plan/2 ]).
:- use_module('../../next/2_lower/lower', [ lower_program/2, boot_statements/7 ]).
:- use_module('../../emit_rust', [ emit_program/5 ]).

:- dynamic(emit_test_dir/1).
:- prolog_load_context(directory, Here), assertz(emit_test_dir(Here)).

fixture_file(File) :-
    emit_test_dir(Dir),
    atomic_list_concat([Dir, '/../../conformance/fixtures/body_words.pl'], File).

% Compile the fixture and emit the Rust module text.
run_emit(Name, Text) :-
    fixture_file(File),
    read_fixture_term(File, Name, Term, Bindings),
    program_plan(Term-Bindings, Plan),
    lower_program(Plan, Lowered),
    Term = fixture(_, _, Initial, _, _),
    Plan = plan(_, prog(Decls, _), Types, RelPlans, _, _, _, _, Mode),
    Lowered = lowered(_, _, _, _, LevelStatements, _, _, _),
    boot_statements(Mode, Decls, Types, RelPlans, Initial, LevelStatements, Boot),
    emit_program(Name, Plan, Lowered, Boot, Text).

% The JSON body is everything between the r#" delim and the closing "#; .
program_json(Text, Json) :-
    sub_atom(Text, Start, _, _, 'r#"'),
    AfterStart is Start + 3,
    sub_atom(Text, JsonStart, 3, _, '"#;'),
    JsonStart >= AfterStart,
    JsonLen is JsonStart - AfterStart,
    sub_atom(Text, AfterStart, JsonLen, _, JsonText),
    open_string(JsonText, Stream),
    json_read(Stream, Json),
    close(Stream).

json_val(Json, Key, Value) :-
    Json = json(Pairs),
    memberchk(Key=Value, Pairs).

:- begin_tests(emit_rust).

test(next_level_emits_rust_document) :-
    run_emit(next_level_is_the_bare_atom_spelling, Text),
    atom_concat('// GENERATED by v6/prolog/emit_rust.pl', _, Text),
    sub_atom(Text, _, _, _, 'pub fn program() -> ProgramJson').

test(next_level_program_name) :-
    run_emit(next_level_is_the_bare_atom_spelling, Text),
    program_json(Text, Json),
    json_val(Json, name, 'next_level_is_the_bare_atom_spelling').

test(next_level_level_support_sql_present) :-
    run_emit(next_level_is_the_bare_atom_spelling, Text),
    program_json(Text, Json),
    json_val(Json, levels, Levels),
    Levels = [Level],
    json_val(Level, head_rel, seen),
    json_val(Level, support_sql, Support),
    length(Support, 11).

test(next_level_intern_mode_dict) :-
    run_emit(next_level_is_the_bare_atom_spelling, Text),
    program_json(Text, Json),
    json_val(Json, intern_mode, dict).

:- end_tests(emit_rust).
