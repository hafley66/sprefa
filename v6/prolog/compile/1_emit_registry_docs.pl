arrival_executor_table(Table) :-
    findall(Line, ( arrival_executor(Name, Executor), two_col_row(Line, Name, Executor) ), RowLines),
    atomic_list_concat(['| arrival rel | executor |\n', '|---|---|\n' | RowLines], Table).

host_input_contract_table(Table) :-
    findall(Line,
            ( host_input_contract(Name, Inputs, Roles),
              three_col_row(Line, Name, Inputs, Roles)
            ),
            RowLines),
    atomic_list_concat(['| host input | columns | roles |\n', '|---|---|---|\n' | RowLines], Table).

http_route_table(Table) :-
    findall(Line,
            ( http_route(Method, Path, Summary), route_row(Line, Method, Path, Summary) ),
            RowLines),
    atomic_list_concat(['| method | path | summary |\n', '|---|---|---|\n' | RowLines], Table).

route_row(Line, Method, Path, Summary) :-
    format(atom(Line), '| `~w` | `~w` | ~w |~n', [Method, Path, Summary]).

two_col_row(Line, A, B) :-
    format(atom(BText), '~q', [B]),
    format(atom(Line), '| `~w` | `~w` |~n', [A, BText]).

three_col_row(Line, A, B, C) :-
    format(atom(BText), '~q', [B]),
    format(atom(CText), '~q', [C]),
    format(atom(Line), '| `~w` | `~w` | `~w` |~n', [A, BText, CText]).
