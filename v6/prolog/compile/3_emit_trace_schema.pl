% Generate the target-neutral DL_PERF_LOG wire schema consumed by tsv2/runtime.
%
% Run:
%   swipl -q -l v6/prolog/compile/3_emit_trace_schema.pl \
%     -g emit_trace_schema -g halt

:- module(emit_trace_schema,
          [ emit_trace_schema/0,
            trace_schema_text/1
          ]).

:- use_module('../0_dot_expand/registry', [trace_event/2]).

:- dynamic(compile_dir/1).
:- prolog_load_context(directory, Here), assertz(compile_dir(Here)).

emit_trace_schema :-
    trace_schema_text(Text),
    compile_dir(Here),
    directory_file_path(Here, '../../../v6/tsv2/runtime/0_traceSchema.ts', Path),
    setup_call_cleanup(open(Path, write, Stream), format(Stream, '~s', [Text]), close(Stream)).

trace_schema_text(Text) :-
    findall(Row, ( trace_event(Name, Fields), event_row(Name, Fields, Row) ), Events),
    atomic_list_concat(Events, '\n', EventText),
    format(string(Text),
'// GENERATED by v6/prolog/compile/3_emit_trace_schema.pl from registry.pl.\n\n/** One field of one DL_PERF_LOG record. `stability` says whether a second\n *  emitter (a rust runtime on `tracing`, say) has to reproduce the value:\n *  stable = yes, byte for byte; timing = a clock; host = target-specific text. */\nexport interface ITraceField {\n  readonly key: string;\n  readonly type: string;\n  readonly stability: "stable" | "timing" | "host";\n}\n\nexport interface ITraceEvent {\n  readonly name: string;\n  readonly fields: readonly ITraceField[];\n}\n\nexport const TRACE_SCHEMA: readonly ITraceEvent[] = [\n~w\n];\n',
           [EventText]).

event_row(Name, Fields, Row) :-
    findall(FieldText, ( member(field(Key, Type, Stability), Fields),
                         field_row(Key, Type, Stability, FieldText) ), FieldTexts),
    atomic_list_concat(FieldTexts, ', ', Inner),
    format(atom(Row), '  { name: "~w", fields: [~w] },', [Name, Inner]).

field_row(Key, Type, Stability, Text) :-
    format(atom(Text), '{ key: "~w", type: "~w", stability: "~w" }', [Key, Type, Stability]).
