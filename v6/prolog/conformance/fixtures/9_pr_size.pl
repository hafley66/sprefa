% pr_size.pl — GitHub PR diff size, decoded from the /pulls/N/files response.
fixture(pr_size_decodes_files_and_rolls_up,
  prog([col_type(files_resp/1, body, json),
        col_type(pr_file/3, path, text),
        col_type(pr_file/3, adds, int),
        col_type(pr_file/3, dels, int),
        col_type(in_dir/2, path, text),
        col_type(in_dir/2, dir, text),
        col_type(dir_file/4, dir, text),
        col_type(dir_file/4, path, text),
        col_type(dir_file/4, adds, int),
        col_type(dir_file/4, dels, int),
        col_type(dir_size/4, dir, text),
        col_type(dir_size/4, adds, int),
        col_type(dir_size/4, dels, int),
        col_type(dir_size/4, files, int)],
       [ (pr_file(Path, Adds, Dels) <-
            files_resp(Body),
            decode(Body, spread({filename: Path: text,
                                 additions: Adds: int,
                                 deletions: Dels: int}))),
         (dir_file(Dir, Path, Adds, Dels) <-
            pr_file(Path, Adds, Dels), in_dir(Path, Dir)),
         (dir_size(Dir, sum(Adds), sum(Dels), count(Path)) <-
            dir_file(Dir, Path, Adds, Dels)) ]),
  [ files_resp([ {filename: 'src/a.ts',  additions: 10, deletions: 2},
                 {filename: 'src/b.ts',  additions: 5,  deletions: 1},
                 {filename: 'README.md', additions: 3,  deletions: 0} ]),
    in_dir('src/a.ts', src), in_dir('src/b.ts', src) ],
  [],
  [ final(pr_file/3, [ pr_file('README.md', 3, 0),
                       pr_file('src/a.ts', 10, 2),
                       pr_file('src/b.ts', 5, 1) ]),
    final(dir_size/4, [ dir_size(src, 15, 3, 2) ]) ]).
