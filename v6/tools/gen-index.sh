#!/bin/sh
# Regenerate v6/INDEX.md — a live table of contents of every markdown in v6/.
# Called from .githooks/pre-commit so it stays current at every commit.
# Run standalone:  sh v6/tools/gen-index.sh
set -eu

repo_root=$(git rev-parse --show-toplevel)
cd "$repo_root/v6"
out="INDEX.md"

{
    echo "# v6 INDEX — every markdown, live (generated at commit)"
    echo
    echo "> Auto-generated by \`v6/tools/gen-index.sh\` from the pre-commit hook."
    echo "> Do not hand-edit; edits are overwritten. Jump table first, full header"
    echo "> index (with line numbers) below."
    echo
    echo "## Jump table"
    echo
    echo "| file | lines | title |"
    echo "|---|--:|---|"
    find . -name '*.md' ! -name 'INDEX.md' | grep -v target | grep -v node_modules | sort | while read -r f; do
        rel=${f#./}
        lines=$(wc -l < "$f" | tr -d ' ')
        h1=$(grep -m1 -E '^# ' "$f" 2>/dev/null | sed 's/^# //' | sed 's/|/\\|/g')
        printf '| [%s](%s) | %s | %s |\n' "$rel" "$rel" "$lines" "$h1"
    done
    echo
    echo "## Full header index"
    echo
    find . -name '*.md' ! -name 'INDEX.md' | grep -v target | grep -v node_modules | sort | while read -r f; do
        rel=${f#./}
        echo "### $rel"
        echo '```'
        grep -nE '^#{1,3} ' "$f" 2>/dev/null | sed 's/\t/ /g' || true
        echo '```'
        echo
    done
} > "$out"

echo "gen-index: wrote v6/$out ($(wc -l < "$out" | tr -d ' ') lines)"
