use std::{env, fs, io, path::PathBuf};

#[derive(Debug, Clone)]
struct Field {
    name: String,
    ty: String,
}

#[derive(Debug, Clone)]
struct TypeDecl {
    name: String,
    fields: Vec<Field>,
}

#[derive(Debug, Clone)]
struct Endpoint {
    name: String,
    method: String,
    path: String,
    response: String,
}

#[derive(Debug)]
struct Schema {
    types: Vec<TypeDecl>,
    endpoints: Vec<Endpoint>,
}

fn parse(source: &str) -> Result<Schema, String> {
    let mut types = Vec::new();
    let mut endpoints = Vec::new();
    let mut lines = source.lines().map(str::trim).filter(|line| {
        !line.is_empty() && !line.starts_with("//")
    });

    while let Some(line) = lines.next() {
        if let Some(rest) = line.strip_prefix("type ") {
            let name = rest
                .strip_suffix("{")
                .ok_or_else(|| format!("expected '{{' in {line}"))?
                .trim()
                .to_owned();
            let mut fields = Vec::new();
            loop {
                let field_line = lines.next().ok_or("unterminated type")?;
                if field_line == "}" {
                    break;
                }
                let (field_name, field_type) = field_line
                    .split_once(':')
                    .ok_or_else(|| format!("expected field: Type, got {field_line}"))?;
                fields.push(Field {
                    name: field_name.trim().to_owned(),
                    ty: field_type.trim().to_owned(),
                });
            }
            types.push(TypeDecl { name, fields });
        } else if let Some(rest) = line.strip_prefix("endpoint ") {
            let parts: Vec<_> = rest.split_whitespace().collect();
            if parts.len() != 5 || parts[3] != "->" {
                return Err(format!("expected endpoint name METHOD /path -> Type, got {line}"));
            }
            endpoints.push(Endpoint {
                name: parts[0].to_owned(),
                method: parts[1].to_owned(),
                path: parts[2].to_owned(),
                response: parts[4].to_owned(),
            });
        } else {
            return Err(format!("unknown schema line: {line}"));
        }
    }

    Ok(Schema { types, endpoints })
}

fn rust_type(ty: &str) -> String {
    match ty {
        "String" => "String".to_owned(),
        "Int" => "i64".to_owned(),
        "Bool" => "bool".to_owned(),
        _ if ty.starts_with("Array<") && ty.ends_with('>') => {
            format!("Vec<{}>", rust_type(&ty[6..ty.len() - 1]))
        }
        _ => ty.to_owned(),
    }
}

fn rust_models(schema: &Schema) -> String {
    let mut out = String::from("// generated by bootstrap-typegen-lab\n\n");
    for type_decl in &schema.types {
        out.push_str(&format!("#[derive(Debug, Clone)]\npub struct {} {{\n", type_decl.name));
        for field in &type_decl.fields {
            out.push_str(&format!("    pub {}: {},\n", field.name, rust_type(&field.ty)));
        }
        out.push_str("}\n\n");
    }
    out
}

fn json_value_for(ty: &str) -> String {
    match ty {
        "String" => "\"generated\"".to_owned(),
        "Int" => "0".to_owned(),
        "Bool" => "true".to_owned(),
        _ if ty.starts_with("Array<") => "[]".to_owned(),
        _ => "{}".to_owned(),
    }
}

fn json_object(type_name: &str, schema: &Schema) -> String {
    let Some(type_decl) = schema.types.iter().find(|item| item.name == type_name) else {
        return "{}".to_owned();
    };
    let fields = type_decl
        .fields
        .iter()
        .map(|field| format!("\"{}\":{}", field.name, json_value_for(&field.ty)))
        .collect::<Vec<_>>()
        .join(",");
    format!("{{{fields}}}")
}

fn path_params(path: &str) -> Vec<String> {
    let mut params = Vec::new();
    let mut remaining = path;
    while let Some(start) = remaining.find('{') {
        let after_start = &remaining[start + 1..];
        let Some(end) = after_start.find('}') else {
            break;
        };
        params.push(after_start[..end].to_owned());
        remaining = &after_start[end + 1..];
    }
    params
}

fn route_prefix(path: &str) -> String {
    path.split('{').next().unwrap_or(path).to_owned()
}

fn server_source(schema: &Schema) -> String {
    let mut out = rust_models(schema);
    out.push_str(
        r#"
use std::io::{Read, Write};
use std::net::TcpListener;

fn main() {
    let listener = TcpListener::bind("127.0.0.1:4000").unwrap();
    println!("generated server listening on http://127.0.0.1:4000");
    for stream in listener.incoming() {
        let mut stream = stream.unwrap();
        let mut request = [0; 4096];
        let size = stream.read(&mut request).unwrap();
        let request = String::from_utf8_lossy(&request[..size]);
        let method = request.split_whitespace().next().unwrap_or("");
        let path = request.split_whitespace().nth(1).unwrap_or("/");
        let (status, body) = route(method, path);
        let response = format!(
            "HTTP/1.1 {status}\r\nContent-Type: application/json\r\nContent-Length: {}\r\nConnection: close\r\n\r\n{body}",
            body.len()
        );
        stream.write_all(response.as_bytes()).unwrap();
    }
}

"#,
    );
    out.push_str(&format!("fn route(method: &str, path: &str) -> (&'static str, String) {{\n"));
    for endpoint in &schema.endpoints {
        let body = json_object(&endpoint.response, schema);
        let prefix = route_prefix(&endpoint.path);
        let matcher = if endpoint.path.contains('{') {
            format!("path.starts_with(\"{prefix}\")")
        } else {
            format!("path == \"{}\" ", endpoint.path)
        };
        out.push_str(&format!(
            "    if method == \"{}\" && {} {{\n        return (\"200 OK\", r#\"{}\"#.to_owned());\n    }}\n",
            endpoint.method, matcher.trim(), body
        ));
    }
    out.push_str("    (\"404 Not Found\", r#\"{\"error\":\"not found\"}\"#.to_owned())\n}\n");
    out
}

fn js_client(schema: &Schema) -> String {
    let mut out = String::from("// generated by bootstrap-typegen-lab\n\nconst baseUrl = \"http://127.0.0.1:4000\";\n\n");
    for endpoint in &schema.endpoints {
        let params = path_params(&endpoint.path);
        let mut path = endpoint.path.clone();
        for param in &params {
            path = path.replace(
                &format!("{{{param}}}"),
                &format!("\" + encodeURIComponent({param}) + \""),
            );
        }
        let args = params.join(", ");
        let fetch_options = if endpoint.method == "GET" {
            String::new()
        } else {
            format!(", {{ method: \"{}\" }}", endpoint.method)
        };
        out.push_str(&format!(
            "export async function {}({args}) {{\n  const response = await fetch(baseUrl + \"{path}\"{fetch_options});\n  if (!response.ok) throw new Error(\"HTTP \" + response.status);\n  return await response.json();\n}}\n\n",
            endpoint.name
        ));
    }
    out
}

fn js_smoke(schema: &Schema) -> String {
    let Some(endpoint) = schema.endpoints.first() else {
        return String::new();
    };
    let args = path_params(&endpoint.path)
        .iter()
        .map(|_| "\"abc\"")
        .collect::<Vec<_>>()
        .join(", ");
    format!(
        "import {{ {} }} from \"./client.mjs\";\nconsole.log(JSON.stringify(await {}({args})));\n",
        endpoint.name, endpoint.name
    )
}

fn stage1_source(schema: &Schema) -> String {
    let mut out = rust_models(schema);
    out.push_str(
        r#"
use std::{env, fs};

struct Schema {
    types: Vec<TypeDecl>,
    endpoints: Vec<Endpoint>,
}

fn parse(source: &str) -> Result<Schema, String> {
    let mut types = Vec::new();
    let mut endpoints = Vec::new();
    let mut lines = source.lines().map(str::trim).filter(|line| {
        !line.is_empty() && !line.starts_with("//")
    });
    while let Some(line) = lines.next() {
        if let Some(rest) = line.strip_prefix("type ") {
            let name = rest.strip_suffix("{").ok_or("expected type brace")?.trim().to_owned();
            let mut fields = Vec::new();
            loop {
                let field_line = lines.next().ok_or("unterminated type")?;
                if field_line == "}" { break; }
                let (field_name, field_type) = field_line.split_once(':').ok_or("expected field")?;
                fields.push(Field { name: field_name.trim().to_owned(), type_name: field_type.trim().to_owned() });
            }
            types.push(TypeDecl { name, fields });
        } else if let Some(rest) = line.strip_prefix("endpoint ") {
            let parts: Vec<_> = rest.split_whitespace().collect();
            if parts.len() != 5 || parts[3] != "->" { return Err("expected endpoint".to_owned()); }
            endpoints.push(Endpoint { name: parts[0].to_owned(), method: parts[1].to_owned(), path: parts[2].to_owned(), response: parts[4].to_owned() });
        } else {
            return Err(format!("unknown line: {line}"));
        }
    }
    Ok(Schema { types, endpoints })
}

fn main() {
    let path = env::args().nth(1).unwrap_or_else(|| "schema.dl".to_owned());
    let source = fs::read_to_string(path).unwrap();
    let schema = parse(&source).unwrap();
    println!("stage1 parsed {} types and {} endpoints", schema.types.len(), schema.endpoints.len());
    println!("generated model type: {}", schema.types[0].name);
}
"#,
    );
    out
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let manifest_dir = env!("CARGO_MANIFEST_DIR");
    let schema_source = fs::read_to_string(PathBuf::from(manifest_dir).join("schema.dl"))?;
    let schema = parse(&schema_source).map_err(io::Error::other)?;
    let output_dir = PathBuf::from(manifest_dir).join("target/bootstrap-generated");
    fs::create_dir_all(&output_dir)?;

    fs::write(output_dir.join("models.rs"), rust_models(&schema))?;
    fs::write(output_dir.join("server.rs"), server_source(&schema))?;
    let client = js_client(&schema);
    fs::write(output_dir.join("client.js"), &client)?;
    fs::write(output_dir.join("client.mjs"), client)?;
    fs::write(output_dir.join("client-smoke.mjs"), js_smoke(&schema))?;
    fs::write(output_dir.join("stage1.rs"), stage1_source(&schema))?;
    println!("generated {} types and {} endpoints", schema.types.len(), schema.endpoints.len());
    println!("output: {}", output_dir.display());
    Ok(())
}
