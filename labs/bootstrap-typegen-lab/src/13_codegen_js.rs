use crate::patterns::{Pattern, PatternPart};
use crate::store::{Declaration, Store};
use crate::types::{Primitive, Type, Value};
use crate::TypeId;

pub fn emit_client(store: &Store) -> String {
    let mut out = String::from("// generated by bootstrap-typegen-lab\n\nconst baseUrl = globalThis.BASE_URL ?? \"http://127.0.0.1:4000\";\n\n");
    for (domain, operation, pattern, output) in &store.consumers {
        if domain == "http" {
            let pattern = &store.patterns[pattern.0 as usize];
            let slots = pattern
                .parts
                .iter()
                .filter_map(|part| match part {
                    PatternPart::Slot(slot) => {
                        Some(store.symbols.resolve(slot.name.unwrap()).to_owned())
                    }
                    _ => None,
                })
                .collect::<Vec<_>>();
            let expression = js_path(pattern, store);
            let args = slots.join(", ");
            out.push_str(&format!("/** @returns {{Promise<{}>}} */\nexport async function {operation}({args}) {{\n  const response = await fetch(baseUrl + {expression});\n  if (!response.ok) throw new Error(\"HTTP \" + response.status);\n  return await response.json();\n}}\n\n", js_type(store, *output)));
        }
    }
    out
}

pub fn emit_models(store: &Store) -> String {
    let mut out = String::from("// generated JavaScript declarations\n\n");
    for (name, declaration) in &store.declarations {
        if let Declaration::Type(id) = declaration {
            out.push_str(&format!(
                "/** @typedef {{{}}} {} */\n",
                js_type(store, *id),
                store.symbols.resolve(*name)
            ));
        }
    }
    out
}

pub fn emit_smoke(store: &Store) -> String {
    store.consumers.first().map(|(_, operation, pattern, _)| { let args = store.patterns[pattern.0 as usize].parts.iter().filter_map(|part| matches!(part, PatternPart::Slot(_)).then_some("\"sample\"".to_owned())).collect::<Vec<_>>().join(", "); format!("import {{ {operation} }} from \"./client.mjs\";\nconsole.log(JSON.stringify(await {operation}({args})));\n") }).unwrap_or_default()
}

fn js_path(pattern: &Pattern, store: &Store) -> String {
    let mut out = String::from("`");
    for part in &pattern.parts {
        match part {
            PatternPart::Literal { text, .. } => out.push_str(&text.replace('`', "\\`")),
            PatternPart::Slot(slot) => out.push_str(&format!(
                "${{encodeURIComponent({})}}",
                store.symbols.resolve(slot.name.unwrap())
            )),
        }
    }
    out.push('`');
    out
}
fn js_type(store: &Store, id: TypeId) -> String {
    match &store.types[id.0 as usize] {
        Type::Alias { name, .. } => store.symbols.resolve(*name).to_owned(),
        Type::Primitive(Primitive::String) | Type::Literal(Value::String(_)) => "string".to_owned(),
        Type::Primitive(Primitive::Int) | Type::Literal(Value::Int(_)) => "number".to_owned(),
        Type::Primitive(Primitive::Bool) | Type::Literal(Value::Bool(_)) => "boolean".to_owned(),
        Type::Array(item) => format!("Array<{}>", js_type(store, *item)),
        Type::Map { value, .. } => format!("Record<string, {}>", js_type(store, *value)),
        Type::Optional(inner) => format!("{} | undefined", js_type(store, *inner)),
        Type::Record(record) => store.symbols.resolve(record.name).to_owned(),
        Type::Union(_) => "string".to_owned(),
        Type::Error => "unknown".to_owned(),
    }
}
