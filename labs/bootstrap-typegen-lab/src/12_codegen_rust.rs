use crate::store::{Declaration, Store};
use crate::types::{Primitive, Type, Value};
use crate::TypeId;

pub fn emit_models(store: &Store) -> String {
    let mut out = String::from("// generated by bootstrap-typegen-lab\n\n");
    let mut declarations = store.declarations.iter().collect::<Vec<_>>();
    declarations.sort_by_key(|(name, _)| store.symbols.resolve(**name));
    for (name, declaration) in declarations {
        if let Declaration::Type(id) = declaration {
            emit_decl(store, &mut out, store.symbols.resolve(*name), *id);
        }
    }
    out
}

fn emit_decl(store: &Store, out: &mut String, name: &str, id: TypeId) {
    match &store.types[id.0 as usize] {
        Type::Record(record) => {
            out.push_str(&format!("#[derive(Debug, Clone)]\npub struct {name} {{\n"));
            for field in &record.fields {
                out.push_str(&format!(
                    "    pub {}: {},\n",
                    store.symbols.resolve(field.name),
                    rust_type(store, field.ty)
                ));
            }
            out.push_str("}\n\n");
        }
        Type::Union(items) => {
            out.push_str(&format!("#[derive(Debug, Clone)]\npub enum {name} {{\n"));
            for (index, item) in items.iter().enumerate() {
                let variant = match &store.types[item.0 as usize] {
                    Type::Literal(Value::String(value)) => title(value),
                    Type::Literal(Value::Int(value)) => format!("N{value}"),
                    Type::Literal(Value::Bool(value)) => format!("B{value}"),
                    _ => format!("Variant{index}"),
                };
                out.push_str(&format!("    {variant},\n"));
            }
            out.push_str("}\n\n");
        }
        _ => out.push_str(&format!("pub type {name} = {};\n\n", rust_type(store, id))),
    }
}

pub fn rust_type(store: &Store, id: TypeId) -> String {
    match &store.types[id.0 as usize] {
        Type::Alias { name, .. } => store.symbols.resolve(*name).to_owned(),
        Type::Primitive(Primitive::String) => "String".to_owned(),
        Type::Primitive(Primitive::Int) => "i64".to_owned(),
        Type::Primitive(Primitive::Bool) => "bool".to_owned(),
        Type::Literal(Value::String(_)) => "String".to_owned(),
        Type::Literal(Value::Int(_)) => "i64".to_owned(),
        Type::Literal(Value::Bool(_)) => "bool".to_owned(),
        Type::Array(item) => format!("Vec<{}>", rust_type(store, *item)),
        Type::Map { key, value } => format!(
            "std::collections::BTreeMap<{}, {}>",
            rust_type(store, *key),
            rust_type(store, *value)
        ),
        Type::Optional(inner) => format!("Option<{}>", rust_type(store, *inner)),
        Type::Record(record) => store.symbols.resolve(record.name).to_owned(),
        Type::Union(_) => "String".to_owned(),
        Type::Error => "()".to_owned(),
    }
}
pub fn title(value: &str) -> String {
    let mut chars = value.chars();
    match chars.next() {
        Some(first) => first.to_uppercase().collect::<String>() + chars.as_str(),
        None => "Empty".to_owned(),
    }
}
