#!/usr/bin/env python3
"""Writes the generated string kernel files from `std/str_ops_emit.dl7`.

`dl8 compile` renders one text row per generated line (`rendered`). Hand steps
this script performs because `fs.file` and the ordered-join aggregate are not
built: reading `compiler_rows`, ordering by (section, index, position), joining
lines (INLINE sections join a op's positions on one line, the rest join with
newlines), and wrapping each section in the Rust shell below.

    python3 scripts/emit_str_ops.py [--check]
"""
import json
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DL8 = os.environ.get("DL8") or str(
    Path(os.environ.get("CARGO_TARGET_DIR", ROOT / "target")) / "debug" / "dl8"
)
IVM_TARGET = ROOT / "sqlite_ivm/crates/ivm-ir/src/3_str_ops.rs"
DL8_TARGET = ROOT / "src/_6_eval/_4a_str_ops.rs"
INLINE = {"ir_args", "dl8_typed"}

IVM_TEMPLATE = """\
//! Generated by scripts/emit_str_ops.py from std/str_ops.dl7. Do not edit.
use crate::{StrKind, StrOut, StrVal};
use serde::{Deserialize, Serialize};

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub enum StrOp {
@ir_variant@
}

impl StrOp {
    pub const ALL: &'static [StrOp] = &[
@ir_all@
    ];

    pub fn name(self) -> &'static str {
        match self {
@ir_name@
        }
    }

    pub fn from_name(name: &str) -> Option<StrOp> {
        match name {
@ir_from_name@
            _ => None,
        }
    }

    pub fn args(self) -> &'static [StrKind] {
        match self {
@ir_args@
        }
    }

    pub fn out(self) -> StrKind {
        match self {
@ir_out@
        }
    }

    pub fn apply(self, args: &[StrVal]) -> Option<StrOut> {
        use crate::{int, text};
        use StrOut::{Int, Text};
        match self {
@ir_apply@
        }
    }
}
"""

DL8_TEMPLATE = """\
//! Generated by scripts/emit_str_ops.py from std/str_ops.dl7. Do not edit.
use ivm_ir::StrOp;

/// `(label, arity, op)` of every `str.<label>` function op.
pub const STR_OPS: &[(&str, usize, StrOp)] = &[
@dl8_table@
];

pub const STR_KERNEL_RELATIONS: &[(Option<&str>, &str, i64)] = &[
@dl8_relation@
];

pub fn str_slot_label(label: &str, index: u32) -> Option<&'static str> {
    Some(match (label, index) {
@dl8_slot@
        _ => return None,
    })
}

pub const STR_TYPED_OPS: &[(&str, &str, &[(&str, &str)])] = &[
@dl8_typed@
];
"""


def payload(term):
    value = term["args"][0]
    return value["s"] if isinstance(value, dict) else value


def rendered():
    out = subprocess.run(
        [DL8, "compile", "./std/str_ops_emit.dl7"],
        cwd=ROOT, check=True, capture_output=True,
    ).stdout
    compiled = json.loads(out)
    if compiled["diagnostics"]:
        sys.exit(f"diagnostics: {compiled['diagnostics']}")
    relation = compiled["program"]["names"]["rendered"]
    rows = [
        [payload(arg) for arg in row["args"][1]]
        for row in compiled["compiler_rows"]
        if row["args"][0] == relation
    ]
    return sorted(rows, key=lambda row: (row[0], row[1], row[2]))


def sections(rows):
    grouped = {}
    for section, index, _position, text in rows:
        grouped.setdefault(section, {}).setdefault(index, []).append(text)
    return {
        section: "\n".join(
            ("" if section in INLINE else "\n").join(lines)
            for _index, lines in sorted(by_index.items())
        )
        for section, by_index in grouped.items()
    }


def fill(template, texts):
    for section, text in texts.items():
        template = template.replace(f"@{section}@", text)
    return template


def main():
    texts = sections(rendered())
    targets = [(IVM_TARGET, IVM_TEMPLATE), (DL8_TARGET, DL8_TEMPLATE)]
    stale = False
    for path, template in targets:
        body = fill(template, texts)
        if "--check" in sys.argv:
            stale |= not path.exists() or path.read_text() != body
        else:
            path.write_text(body)
    if stale:
        sys.exit("generated files are stale; run scripts/emit_str_ops.py")


main()
