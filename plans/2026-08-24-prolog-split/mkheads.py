"""mkheads.py -- the exact include block each module head grows.

Reads every cuts file, resolves the head's last line the way partition.py does,
and prints one block per target.
"""

import json
import os
from glob import glob

print("# module head include blocks\n")
print("Generated by `mkheads.py` from the cut files. Paste each block verbatim")
print("below the last directive of the module head it names.\n")
for path in sorted(glob('cuts/*.cuts.json')):
    cuts = json.load(open(path))
    pm = json.load(open(cuts['predmap']))
    first = {}
    for term in pm['terms']:
        if term['kind'] == 'directive':
            continue
        first.setdefault("%s/%s" % (term['name'], term['arity']), term['start'])
    head = min(first[p['anchor']] for p in cuts['parts'] if p.get('anchor')) - 1
    folder = os.path.basename(cuts['folder'])
    print("## %s\n" % cuts['file'])
    print("head keeps lines 1..%d, then:\n" % head)
    print("```prolog")
    for part in cuts['parts']:
        print(":- include('%s/%s')." % (folder, part['file']))
    print("```\n")
