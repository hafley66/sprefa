import { execFileSync } from "node:child_process";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { emitFacts } from "./1a_fact_emit.mjs";

export const schemaDirectory = dirname(fileURLToPath(import.meta.url));
export const repository = dirname(schemaDirectory);
const outputDirectory = join(schemaDirectory, "generated");

// Resolve the original checkout through Git so linked worktrees use the same
// sibling toolchain. Never install packages or write inside that checkout.
function toolchainRoot() {
  if (process.env.HAFLEY_TSP_ROOT) return resolve(process.env.HAFLEY_TSP_ROOT);
  const common = execFileSync("git", ["rev-parse", "--path-format=absolute", "--git-common-dir"], {
    cwd: repository, encoding: "utf8", timeout: 10_000,
  }).trim();
  return join(dirname(dirname(common)), "hafley-tsp");
}

export async function generate(entry = join(schemaDirectory, "1_sql_trial.tsp")) {
  const root = toolchainRoot();
  const require = createRequire(join(root, "package.json"));
  const compilerPath = require.resolve("@typespec/compiler");
  const compilerPackage = JSON.parse(await readFile(resolve(dirname(compilerPath), "../../package.json"), "utf8"));
  if (compilerPackage.version !== "1.10.0") {
    throw new Error(`Extract schema requires TypeSpec 1.10.0; found ${compilerPackage.version} in ${root}`);
  }
  const { compile, NodeHost, formatDiagnostic, getDoc } = await import(pathToFileURL(compilerPath));
  const binding = join(root, "packages/binding-core");
  const { emitSQL } = await import(pathToFileURL(join(binding, "dist/src/4_emit-sql.js")));
  const { resolveFieldType, snakeCase } = await import(pathToFileURL(join(binding, "dist/src/2_facts.js")));
  const { rustTarget } = await import(pathToFileURL(join(root, "packages/emit-helper/src/3_rust.ts")));
  const { emitAll } = await import(pathToFileURL(join(root, "packages/emit-helper/src/2_walk.ts")));

  // Import declarations and their implementations directly. The library's
  // main entry has an onValidate hook that writes even when noEmit is true.
  const program = await compile(NodeHost, entry, {
    noEmit: true,
    additionalImports: [
      join(binding, "dist/src/decorators.js"),
      join(binding, "lib/entity.tsp"),
    ],
  });
  if (program.diagnostics.length) {
    throw new Error(program.diagnostics.map(diagnostic => formatDiagnostic(diagnostic)).join("\n"));
  }
  const namespace = program.getGlobalNamespaceType().namespaces.get("Extract");
  if (!namespace || namespace.models.size === 0) throw new Error("No Extract models to generate");
  const models = [...namespace.models.values()].map(model => ({
    kind: "model",
    name: model.name,
    doc: getDoc(program, model),
    fields: [...model.properties.values()].map(property => {
      const { typeName } = resolveFieldType(property.type);
      // This checkpoint has only the existing u32 span fields. Unsupported
      // shapes must fail, rather than become TEXT via an emitter fallback.
      if (property.optional || property.type.kind !== "Scalar" || typeName !== "uint32") {
        throw new Error(`Unsupported span field: ${model.name}.${property.name}`);
      }
      return { name: property.name, type: { kind: "scalar", name: typeName } };
    }),
  }));
  const declarations = emitAll(models, rustTarget);
  const files = new Map(models.map((model, index) => [
    `${index}_${snakeCase(model.name)}.rs`,
    `// Generated by just gen from schema/0_spans.tsp. Do not edit.\n${declarations[index].code}\n`,
  ]));
  files.set("2_sql_trial.sql", `-- Generated by just gen from schema/1_sql_trial.tsp. Storage fixtures only.\n${emitSQL(program)}`);
  files.set("3_models.json", JSON.stringify(models, null, 2) + "\n");
  const facts = await compile(NodeHost, join(schemaDirectory, "1_facts.tsp"), {
    noEmit: true,
    additionalImports: [join(binding, "dist/src/decorators.js"), join(binding, "lib/entity.tsp")],
  });
  if (facts.diagnostics.length) throw new Error(facts.diagnostics.map(d => formatDiagnostic(d)).join("\n"));
  for (const [name, content] of emitFacts(facts, emitSQL, rustTarget, emitAll)) files.set(name, content);
  return files;
}

export async function checkGenerated(files) {
  for (const [name, content] of files) {
    let existing;
    try { existing = await readFile(join(outputDirectory, name), "utf8"); }
    catch (error) { if (error.code !== "ENOENT") throw error; }
    if (existing !== content) throw new Error(`Stale generated file: schema/generated/${name}; run just gen`);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const args = process.argv.slice(2);
    if (args.length && (args.length !== 1 || args[0] !== "--check")) {
      throw new Error("usage: node schema/2_gen.mjs [--check]");
    }
    const files = await generate();
    if (args[0] === "--check") {
      await checkGenerated(files);
    } else {
      await mkdir(outputDirectory, { recursive: true });
      for (const [name, content] of files) await writeFile(join(outputDirectory, name), content);
    }
    console.log(`gen: ${files.size} artifacts ${args[0] === "--check" ? "current" : "written"}`);
  } catch (error) {
    console.error(`gen: ${error.message}`);
    process.exitCode = 1;
  }
}
