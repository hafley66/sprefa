#!/usr/bin/env python3
"""build_manifest.py <fixture_dir> <out MANIFEST.json>

Reproducible ground-truth generator for the v2 CTF (capture-the-flag) fixture
(bench/agent-eval/fixtures/ctf-permissions). The answer key for "find every
place the export permission is enforced" is NOT hand-typed line numbers — it is
this script's output: a fixed list of (file, regex, abstraction) enforcement
rules, grepped against the committed fixture. Rerunning it on the same fixture
is byte-stable, and the script IS the audit trail (every gate site is one rule
here). It never calls dl — the key is independent of the tool under test.

Each RULE names a file, an abstraction kind, the concept it gates (export vs the
import decoy), and a literal-ish regex that matches EXACTLY the enforcement
statement's line. A rule that matches a count other than `expect` aborts loudly
so a fixture edit that shifts a gate can never silently corrupt the key.
"""
import json
import re
import sys

# (file, concept, abstraction, lang, regex, expected_match_count)
RULES = [
    # --- export permission: the four abstractions, TS ---
    ("app-ts/src/routes/export.ts", "export", "flag", "ts", r"if \(!user\.canExport\)", 2),
    ("app-ts/src/routes/export.ts", "export", "service", "ts", r"permissions\.require\(user, PERM_EXPORT\)", 2),
    ("app-ts/src/routes/export.ts", "export", "guard", "ts", r"requirePermission\(PERM_EXPORT\)", 1),
    ("app-ts/src/routes/export.ts", "export", "config", "ts", r"enforceConfigRule\(ctx, PERM_EXPORT\)", 1),
    # --- export permission: the four abstractions, Rust ---
    ("app-rs/src/handlers/export.rs", "export", "flag", "rs", r"check_export_flag\(user\)\?", 1),
    ("app-rs/src/handlers/export.rs", "export", "service", "rs", r"perms\.require\(Permission::CanExport\)\?", 1),
    ("app-rs/src/handlers/export.rs", "export", "guard", "rs", r"require_export\(user\)\?", 1),
    ("app-rs/src/handlers/export.rs", "export", "config", "rs", r"enforce_rule\(&ctx, EXPORT_RULE\)\?", 1),
    # --- import permission (DECOY concept, negative-control target) ---
    ("app-ts/src/routes/import.ts", "import", "flag", "ts", r"if \(!user\.canImport\)", 1),
    ("app-ts/src/routes/import.ts", "import", "service", "ts", r"permissions\.require\(user, PERM_IMPORT\)", 1),
    ("app-rs/src/handlers/import.rs", "import", "flag", "rs", r"check_import_flag\(user\)\?", 1),
    ("app-rs/src/handlers/import.rs", "import", "guard", "rs", r"require_import\(user\)\?", 1),
]


def main():
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        raise SystemExit(2)
    fixture_dir, out_path = sys.argv[1:3]

    sites = []
    for rel_file, concept, abstraction, lang, pattern, expect in RULES:
        with open(f"{fixture_dir}/{rel_file}", encoding="utf-8") as f:
            lines = f.readlines()
        rx = re.compile(pattern)
        hits = [i + 1 for i, line in enumerate(lines) if rx.search(line)]
        if len(hits) != expect:
            raise SystemExit(
                f"build_manifest: rule {rel_file} /{pattern}/ expected {expect} "
                f"match(es), found {len(hits)} at lines {hits} — fixture drifted"
            )
        for line in hits:
            sites.append({
                "file": rel_file, "line": line, "concept": concept,
                "abstraction": abstraction, "lang": lang,
            })

    sites.sort(key=lambda s: (s["concept"], s["file"], s["line"]))
    manifest = {
        "fixture": "ctf-permissions",
        "concept": "can_export",
        "window_lines": 2,
        "note": (
            "Ground truth for the v2 CTF pilot. Generated by "
            "bench/agent-eval/build_manifest.py from the committed fixture; the "
            "script's RULES list is the audit trail. Never produced by dl."
        ),
        "sites": sites,
    }
    with open(out_path, "w") as f:
        json.dump(manifest, f, indent=2)
        f.write("\n")

    export_n = sum(1 for s in sites if s["concept"] == "export")
    import_n = sum(1 for s in sites if s["concept"] == "import")
    print(f"build_manifest: {len(sites)} sites "
          f"(export={export_n}, import={import_n}) -> {out_path}", file=sys.stderr)


if __name__ == "__main__":
    main()
