#!/usr/bin/env node
// Render the self-hosted type graph as a d2 "territory map":
//   - each enum becomes a bordered region containing its variants
//   - field / impl / generic edges become arrows between regions
//   - variant edges are dropped (containment already shows them)
//   - high-degree types are thickened (hub); fully-qualified externals ghosted
//
// Usage:  node bin/types-to-d2.mjs [--seed TypeName] > graphs/types.d2
//         (default writes graphs/types.d2, then run `npm run graphs`)
//
// It shells out to the `dl` engine, so the map is always live against v5/src.

import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { writeFileSync, mkdtempSync } from 'node:fs'
import { tmpdir } from 'node:os'
import path from 'node:path'

const animRoot = fileURLToPath(new URL('..', import.meta.url))
const repoRoot = path.resolve(animRoot, '..', '..')      // sprefa/
const dl = path.join(repoRoot, 'v5/target/debug/dl')

const args = process.argv.slice(2)
const seedIx = args.indexOf('--seed')
const seed = seedIx >= 0 ? args[seedIx + 1] : null       // optional: one type's neighbourhood
const outIx = args.indexOf('--out')
const out = outIx >= 0 ? args[outIx + 1] : path.join(animRoot, 'graphs/types.d2')
const HUB_DEGREE = 4

// --- 1. ask the engine for every type_edge -------------------------------
const where = seed ? ` where from = "${seed}"` : ''
const prog = `
rel seen(path: file).
seen(path) <- scan("WORK", "v5/src/**/*.rs", path, rev), match(path, rev, /./, line).
? type_edge(from, to, kind)${where}.
`
const tmp = path.join(mkdtempSync(path.join(tmpdir(), 'typemap-')), 'q.dl')
writeFileSync(tmp, prog)
const raw = execFileSync(dl, [tmp, '--root', repoRoot], { encoding: 'utf8' })

// --- 2. parse the `? type_edge => ...` block -----------------------------
const edges = []                                          // {from, to, kind}
let inBlock = false
for (const line of raw.split('\n')) {
  if (line.startsWith('? type_edge')) { inBlock = true; continue }
  if (!inBlock) continue
  if (/^\s*\(\d+ rows?\)/.test(line)) break
  const cols = line.replace(/^\s+/, '').split('\t')
  if (cols.length === 3) edges.push({ from: cols[0], to: cols[1], kind: cols[2] })
}

// --- 3. shape the graph --------------------------------------------------
const owners = new Set(edges.filter(e => e.kind === 'variant').map(e => e.from))
const nodes = new Set()
for (const e of edges) { nodes.add(e.from); nodes.add(e.to) }

const ownerOf = (n) => {
  const i = n.indexOf('::')
  if (i < 0) return null
  const head = n.slice(0, i)
  return owners.has(head) ? head : null
}
const isExternal = (n) => ownerOf(n) === null && n.includes('::') // std::… crate::…

// --- JSON mode: emit {nodes, edges} for the interactive explorer ---------
if (args.includes('--json')) {
  const indeg = new Map(), outdeg = new Map()
  for (const e of edges) {
    outdeg.set(e.from, (outdeg.get(e.from) || 0) + 1)
    indeg.set(e.to, (indeg.get(e.to) || 0) + 1)
  }
  const jnodes = [...nodes].sort().map(id => ({
    id,
    label: ownerOf(id) ? id.slice(ownerOf(id).length + 2) : id,
    owner: ownerOf(id),
    isOwner: owners.has(id),
    external: isExternal(id),
    indeg: indeg.get(id) || 0,
    outdeg: outdeg.get(id) || 0,
  }))
  const jedges = edges.map(e => ({ source: e.from, target: e.to, kind: e.kind }))
  const jout = path.join(animRoot, 'public/types.json')
  writeFileSync(jout, JSON.stringify({ nodes: jnodes, edges: jedges }, null, 0))
  console.error(`wrote ${jout}  (${jnodes.length} nodes, ${jedges.length} edges)`)
  process.exit(0)
}

// d2 path for a node: "Owner"."variant"  |  "Name"
const pathOf = (n) => {
  const o = ownerOf(n)
  return o ? `"${o}"."${n.slice(o.length + 2)}"` : `"${n}"`
}
const labelOf = (n) => {
  const o = ownerOf(n)
  return o ? n.slice(o.length + 2) : n
}

// degree (non-variant edges only) → hubs
const deg = new Map()
const bump = (n) => deg.set(n, (deg.get(n) || 0) + 1)
const arrows = edges.filter(e => e.kind !== 'variant')
for (const e of arrows) { bump(e.from); bump(e.to) }
const classesFor = (n) => {
  const c = ['type']
  if ((deg.get(n) || 0) >= HUB_DEGREE) c.push('hub')
  if (isExternal(n)) return isExternal(n) ? ['ghost'] : c // externals read as faded leaves
  return c
}

// --- 4. emit d2 ----------------------------------------------------------
const KIT = `# generated by bin/types-to-d2.mjs — do not hand-edit; \`npm run graphs\` renders it.
classes: {
  type:   { shape: hexagon;   style: { fill: "#a3be8c"; stroke: "#2e3440" } }
  hub:    { style: { stroke-width: 3 } }
  ghost:  { style: { opacity: 0.45; stroke-dash: 3 } }
}
direction: right
`
const L = [KIT]

// territories first (enum owners with their variants nested)
for (const owner of [...owners].sort()) {
  L.push(`"${owner}": {`)
  L.push(`  class: type`)
  for (const n of [...nodes].filter(x => ownerOf(x) === owner).sort()) {
    L.push(`  "${labelOf(n)}"`)
  }
  L.push(`}`)
}
// plain + external nodes
for (const n of [...nodes].sort()) {
  if (ownerOf(n) || owners.has(n)) continue
  L.push(`${pathOf(n)}.class: [${classesFor(n).join('; ')}]`)
}
// arrows
const seen = new Set()
for (const e of arrows) {
  const key = `${e.from}\x1f${e.to}`
  if (seen.has(key)) continue
  seen.add(key)
  L.push(`${pathOf(e.from)} -> ${pathOf(e.to)}`)
}

writeFileSync(out, L.join('\n') + '\n')
console.error(`wrote ${out}  (${nodes.size} types, ${owners.size} territories, ${seen.size} edges)`)
